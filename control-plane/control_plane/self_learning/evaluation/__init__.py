"""`control_plane.self_learning.evaluation` -- the Evaluation Foundation
(docs/IMPLEMENTATION-ROADMAP.md Phase 9.3): Baseline -> Benchmark ->
Metrics; Candidate -> same Benchmark -> Metrics; Compare -> Pass/Fail,
built once here for every learning level (9.4+) to reuse.

**Scope (this phase)**: comparison/metrics mechanism only -- no candidate
is generated by this package (a candidate's `EvaluationSubjectResult` is
always supplied by the caller, already produced elsewhere), no
autonomous promotion, no deployment (docs/IMPLEMENTATION-ROADMAP.md Phase
9.3's own Non-Goals). Evaluation is evidence, not authorization: nothing
in this package invokes a tool, grants access to tenant data beyond what
the caller already supplied, or has any authority over RBAC, security
policy, secrets policy, or autonomy-tier policy (same "does not grant
policy authority" discipline `control_plane.self_learning`'s own
Learning Authorization gate follows, ADR-0014).

Owns:
- `Benchmark` / `EvaluationMetrics` / `EvaluationSubjectResult` --
  immutable (frozen dataclass) evidence shapes (`models.py`);
- `MetricThreshold` / `EvaluationRules` -- typed comparison rules;
- `EvaluationOutcome` / `EvaluationInvalidReason` / `EvaluationComparison`
  -- the four-state, never-silently-PASS verdict shape;
- `evaluate_candidate()` -- the pure comparison function;
- `run_evaluation()` -- the audited entrypoint (`learning.evaluation_run`,
  Phase 9.3's own Audit Requirement).

Does NOT own: Learning Authorization or Data Authorization (this package
*consumes* an already-ALLOW `LearningAuthorizationDecision` per subject,
never re-derives one -- `control_plane.self_learning.service`,
`control_plane.data_authorization`); candidate generation, adaptive
learning, system learning, experimentation, autonomy/policy-gate
promotion, or autonomous deployment (Phase 9.4-9.9, not built here); the
Learning Ledger (still conceptual only, Phase 9.1 -- no persistence is
introduced by this package; every evaluation run is recorded through
`core.audit_log`'s existing interface, never a parallel mechanism).

No database table, migration, or model is defined here -- `Benchmark`,
`EvaluationMetrics`, `EvaluationSubjectResult`, `EvaluationRules`, and
`EvaluationComparison` are all plain in-memory dataclasses, exactly like
`control_plane.data_authorization`'s and
`control_plane.self_learning.service`'s own no-persistence discipline
(Phase 9.2).
"""

