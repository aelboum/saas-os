"""The transactional outbox table (Foundation Reliability & Events, RE-1).

`core.outbox_events` is tenant-owned and RLS-protected: every row belongs to
exactly one tenant, named by `tenant_id`, and is written by
`saas_os.core.outbox.append_event()` inside the *caller's own* tenant-scoped
transaction -- the same transaction as the business mutation that caused
it. There is no system-owned row: every current producer
(`saas_os.core.webhooks`, `saas_os.core.usage`, `saas_os.core.notifications`) is tenant-scoped, so
no ambiguous "optional tenant" column exists; a future system event needs
its own explicitly classified table, never a nullable `tenant_id` here.

Columns beyond the event itself (`status`, `attempts`, `next_attempt_at`,
`last_error`, `published_at`, `claim_token`) are the dispatch state the
durable dispatcher maintains (RE-2, `saas_os/core/outbox/dispatch.py`).
`append_event()` writes a row in its initial state (`pending`, 0 attempts,
unclaimed, `next_attempt_at` = creation time).

`id` is the stable event identity: generated once, when the row is
appended, and never regenerated by any retry, restart or re-dispatch. The
contract is durable, at-least-once publication with a stable identity --
not exactly-once delivery.
"""

from __future__ import annotations

import uuid
from datetime import datetime

from saas_os.infra.db import (
    JSON,
    Base,
    CheckConstraint,
    DateTime,
    ForeignKey,
    Integer,
    Mapped,
    String,
    TimestampMixin,
    UUIDPrimaryKeyMixin,
    mapped_column,
    now,
)

OUTBOX_STATUS_PENDING = "pending"
OUTBOX_STATUS_PUBLISHED = "published"
OUTBOX_STATUS_DEAD_LETTERED = "dead_lettered"
OUTBOX_STATUSES = (OUTBOX_STATUS_PENDING, OUTBOX_STATUS_PUBLISHED, OUTBOX_STATUS_DEAD_LETTERED)


class OutboxEvent(Base, UUIDPrimaryKeyMixin, TimestampMixin):
    __tablename__ = "outbox_events"
    __table_args__ = (
        CheckConstraint(
            "status IN ('pending', 'published', 'dead_lettered')",
            name="ck_outbox_events_status",
        ),
        CheckConstraint("attempts >= 0", name="ck_outbox_events_attempts_non_negative"),
        CheckConstraint(
            "claim_token IS NULL OR status = 'pending'",
            name="ck_outbox_events_claim_only_pending",
        ),
        {"schema": "core"},
    )

    tenant_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("core.tenants.id"), nullable=False, index=True
    )
    event_type: Mapped[str] = mapped_column(String(100), nullable=False)
    aggregate_type: Mapped[str] = mapped_column(String(100), nullable=False)
    aggregate_id: Mapped[str] = mapped_column(String(255), nullable=False)
    payload: Mapped[dict] = mapped_column(JSON, nullable=False)
    correlation_id: Mapped[str | None] = mapped_column(String(100), nullable=True)
    status: Mapped[str] = mapped_column(String(20), nullable=False, default=OUTBOX_STATUS_PENDING)
    attempts: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    next_attempt_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=now()
    )
    last_error: Mapped[str | None] = mapped_column(String(500), nullable=True)
    published_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)
    # RE-2: the dispatcher claim that owns this pending event, if any; while
    # set, `next_attempt_at` is the claim's lease expiry (saas_os/core/outbox/dispatch.py).
    claim_token: Mapped[uuid.UUID | None] = mapped_column(nullable=True)


class OutboxConsumption(Base):
    """One completed consumption of an outbox event by one consumer
    (Reliability & Events RE-5, `saas_os/core/outbox/consumption.py`).

    The primary key is the logical idempotency identity: `(tenant_id,
    consumer, event_id)`. A row exists only once its consumer's transaction
    committed -- an in-flight claim is this row *uncommitted*, which
    PostgreSQL itself holds (a concurrent claimant of the same identity
    waits on it) and discards on rollback. No payload, no result, no
    secret: just the identity and when it was consumed."""

    __tablename__ = "outbox_consumptions"
    __table_args__ = ({"schema": "core"},)

    tenant_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("core.tenants.id"), primary_key=True)
    consumer: Mapped[str] = mapped_column(String(100), primary_key=True)
    event_id: Mapped[uuid.UUID] = mapped_column(primary_key=True)
    consumed_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=now()
    )
