"""create the platform audit subject reference tables

Revision ID: e2b7c4d9a1f6
Revises: f0cc2e656d79
Create Date: 2026-11-04 12:00:00.000000

Phase P1 of the audit identity work (docs/architecture/
AUDIT-USER-IDENTIFIER-RETENTION-PROPOSAL.md sections 4.3 and 4.4, platform
variants; owner decisions D1, D6, O2, O6, OD-2 and, on 2026-11-04, option A1
of docs/architecture/AUDIT-P1-FOREIGN-KEY-OPTIONS.md). Three new, global,
platform-owned tables; nothing existing changes.

`core.platform_audit_subject_links` maps a random, non-identifying reference
(`subject_ref`, `gen_random_uuid()`) to a user, one live link per user and
UTC calendar day (D1). A new platform audit row that targets a user stores
the reference, never the user id (`target_type = 'user_subject'`). A link is
unlinked (never deleted by the application) by identity erasure or by the
expiry command of a later phase: `user_id` becomes NULL, `unlinked_at` and
`unlink_reason` are set, and the reference stays in the audit row but names
nobody. `core.platform_audit_subject_erasures` holds one marker per erased
user so a later audit write for that user gets an unlinkable reference.
`core.platform_audit_identity_holds` is the legal-hold table of the expiry
design (proposal 4.9); nothing writes it in this phase.

SQL reviewed on PostgreSQL 16 (docs/architecture/AUDIT-P1-SQL-REVIEW.md):
the DDL below is that review's DDL, with the corrections it lists (named
foreign keys; the marker table's columns; the one-way trigger written out).

Global tables with the tenant-context exclusion policy of the platform
tables (`c4a9e1f07b52`, ADR-0045 section 9b): no tenant-bound transaction can
read or change them. The foreign keys to `core.users` are `NO ACTION`; no
application path deletes a user and the platform writers hold
`SELECT ... FOR KEY SHARE` on the user row while they decide existence
(option A1), so an unknown id never reaches the constraint.

Grants. The runtime role keeps SELECT and INSERT from `e99c76057719`'s
default privileges and nothing else is widened: on the link table it may
UPDATE only `user_id`, `unlinked_at` and `unlink_reason` (an unlink); on the
marker table nothing beyond SELECT and INSERT; on the hold table only the two
release columns. DELETE and TRUNCATE are never granted. Two `BEFORE UPDATE`
triggers (no SECURITY DEFINER, fixed search_path) refuse, for every role
including the migrations role, any UPDATE that is not live -> unlinked on a
link and any UPDATE of a released hold (`check_violation`). The triggers
guard UPDATE only: the table owner (the migrations role) can still DELETE or
TRUNCATE, or disable the triggers; that is a privileged, audited operation
outside the application, not something the database prevents. Likewise the
database does not enforce legal holds: the hold table only records them, and
it is the application code (the erasure step now, the expiry command later)
that reads it and refuses to unlink a held link.

Locks and data safety. New, empty tables; no backfill, no existing row
changes. `lock_timeout` is 5s for the migration transaction (as in
0420025c3b4b and f0cc2e656d79), so a long writer on `core.users` fails the
migration instead of queueing everything behind it. Creating the two tables
that reference `core.users` takes
`SHARE ROW EXCLUSIVE` on `core.users` until the migration transaction ends
(reads continue, writes to `core.users` wait); the transaction is
milliseconds long. `core.tenants` is not referenced. Existing audit rows and
the ADR-0053 digests are untouched: a row written before this migration
keeps its raw target id (D5).

Downgrade refuses while any of the three tables holds a row: the link table
is the only way to resolve a reference already written to the audit log, a
marker is erasure evidence, and a hold is retention evidence, so none is
dropped silently. With the tables empty it drops them and the two trigger
functions. Removing rows to allow a downgrade is a separately approved
manual procedure. The downgrade locks the three tables (`ACCESS EXCLUSIVE`,
bounded by the same `lock_timeout`) before it counts rows, so an insert
cannot slip in between the check and the DROP. Hand-written, not
autogenerated.
"""

