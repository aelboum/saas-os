def downgrade() -> None:
    # Lock first, then look: an insert in flight either commits before the
    # lock is granted (and the check sees its row) or waits until the tables
    # are gone. ACCESS EXCLUSIVE also blocks a writer's FOR KEY SHARE read.
    op.execute("SET LOCAL lock_timeout = '5s'")
    op.execute(
        "LOCK TABLE "
        + ", ".join(f"core.{table}" for table in _TABLES)
        + " IN ACCESS EXCLUSIVE MODE"
    )
    # The migrations role sees every row: the exclusion policy admits an
    # untenanted session.
    for table, what in (
        (_LINKS, "audit subject links, the only way to resolve a reference"),
        (_ERASURES, "audit subject erasure markers, erasure evidence"),
        (_HOLDS, "audit identity holds, retention evidence"),
    ):
        op.execute(
            "DO $$ BEGIN "
            f"IF EXISTS (SELECT 1 FROM core.{table}) THEN "
            f"RAISE EXCEPTION 'core.{table} holds {what}; refusing to drop it. "
            "See docs/RUNBOOKS.md, audit subject references, deliberate downgrade.'; "
            "END IF; END $$"
        )
    # Dropping a table drops its policy, indexes, trigger and privileges.
    for table in _TABLES:
        op.drop_table(table, schema="core")
    op.execute("DROP FUNCTION core.platform_audit_subject_links_one_way()")
    op.execute("DROP FUNCTION core.platform_audit_identity_holds_release_once()")
