"""create the tenant audit subject reference tables

Revision ID: c7e3a9f2b4d8
Revises: b6d2f8a4c1e7
Create Date: 2026-11-15 12:00:00.000000

Phase P3a of the audit identity work (docs/architecture/
AUDIT-IDENTITY-P3-PLAN.md, migration M1; docs/architecture/
AUDIT-USER-IDENTIFIER-RETENTION-PROPOSAL.md sections 4.3, 4.4, 4.6 and 4.9,
tenant variants; owner decisions D1, D2, D4, OD-3 and ADR-0063 option A).
Three new, tenant-owned tables; nothing existing changes.

`core.audit_subject_links` maps a random, non-identifying reference
(`subject_ref`, `gen_random_uuid()`) to a user **within one tenant**, one
live link per tenant, user and UTC calendar day (D1). A tenant audit row
that names a user through a reference stores the reference, never the user
id. A link is unlinked (never deleted by the application) by identity
erasure or by the expiry command: `user_id` becomes NULL, `unlinked_at` and
`unlink_reason` are set, and the reference stays in the audit row but names
nobody. `core.audit_subject_erasures` holds one marker per erased user and
tenant, so a later audit write for that user in that tenant gets an
unlinkable reference. `core.audit_identity_holds` is the tenant legal-hold
table (proposal 4.9); nothing writes it in this phase (the hold routes and
their evidence check come with phase P3c), and the erasure step reads it.

Tenant-owned tables under the canonical tenant policy
(`tenant_rls_statements()`, `ENABLE` and `FORCE`): a transaction bound to
tenant A sees and writes only tenant A's rows, and an untenanted
transaction sees none. Every query in Core also names the tenant
explicitly (proposal 4.3, item 3).

Grants (ADR-0063, option A, accepted 2026-11-15). The runtime role keeps
SELECT and INSERT from `e99c76057719`'s default privileges and nothing else
is widened: on the link table it may UPDATE only `user_id`, `unlinked_at`
and `unlink_reason` (an unlink); on the marker table nothing beyond SELECT
and INSERT; on the hold table only the two release columns. DELETE and
TRUNCATE are never granted. Two `BEFORE UPDATE` triggers (no SECURITY
DEFINER, fixed search_path) refuse, for every role including the migrations
role, any UPDATE that is not live -> unlinked on a link and any UPDATE of a
released hold (`check_violation`). The database does not enforce legal
holds: the application code (the erasure step, the expiry command) reads
them and refuses to unlink a held link.

Locks and data safety. New, empty tables; no backfill, no existing row
changes. `lock_timeout` is 5s for the migration transaction (as in
`e2b7c4d9a1f6`). The foreign keys to `core.tenants` and `core.users` take
`SHARE ROW EXCLUSIVE` on those two tables until the migration transaction
ends (reads continue, writes wait); the transaction is milliseconds long.
Existing audit rows and the ADR-0053 digests are untouched: a row written
before this migration keeps its shape (D5). Both foreign keys are safe
under tenant purge and erasure: a purged tenant keeps its tombstone row,
and Core never deletes a user.

Downgrade refuses while any of the three tables holds a row: the link table
is the only way to resolve a reference already written to a tenant audit
log, a marker is erasure evidence, and a hold is retention evidence.
`FORCE ROW LEVEL SECURITY` binds the migrations role (the owner) too, so an
untenanted `SELECT` would see no rows and the check would pass on a full
table. The downgrade therefore locks the tables `ACCESS EXCLUSIVE`, turns
row-level security off for them **inside its own transaction**, and only
then checks: a refusal rolls back the whole downgrade, including that
change, and a passing check is followed by the DROP in the same
transaction. With the tables empty it drops them and the two trigger
functions. Hand-written, not autogenerated.
"""

