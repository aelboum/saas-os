_REGISTER_INSERT = _fn(
    f"""
DECLARE
    linked core.{REGISTER}%ROWTYPE;
    designation core.{REGISTER}%ROWTYPE;
    revoked_kind text;
BEGIN
    {_LOCK}
    NEW.recorded_at := now();
    NEW.eligible_from := NULL;
    NEW.proposal_expires_at := NULL;
    IF NEW.entry_type = 'representative_designation_proposal' THEN
        IF NEW.valid_until IS NULL OR NEW.valid_until <= now()
           OR NEW.valid_until > now() + interval '12 months' THEN
            {_refuse("a designation is valid for at most 12 months")}
        END IF;
        IF NEW.subject_user_id = NEW.recorded_by_user_id THEN
            {_refuse("a representative is proposed by someone else")}
        END IF;
        IF core.pgl_holds_platform_permission(NEW.subject_user_id, 'platform.authority:manage')
        THEN {_refuse("a holder of platform.authority:manage is never a representative")}
        END IF;
        IF core.pgl_active_enrolment_count(NEW.subject_user_id, NULL, NULL) > 0 THEN
            {_refuse("an approver is never a representative")}
        END IF;
        NEW.proposal_expires_at := now() + interval '72 hours';
    ELSIF NEW.entry_type = 'representative_designation' THEN
        SELECT * INTO linked FROM core.{REGISTER} WHERE id = NEW.proposal_entry_id;
        IF NOT FOUND OR linked.entry_type <> 'representative_designation_proposal' THEN
            {_refuse("a designation confirms a proposal")}
        END IF;
        IF now() >= linked.proposal_expires_at THEN
            {_refuse("the proposal expired")}
        END IF;
        IF EXISTS (SELECT 1 FROM core.{REGISTER} WHERE proposal_entry_id = linked.id) THEN
            {_refuse("the proposal was already confirmed")}
        END IF;
        IF NEW.subject_user_id <> linked.subject_user_id
           OR NEW.recorded_by_user_id IN (linked.recorded_by_user_id, linked.subject_user_id) THEN
            {_refuse("the confirmation is by someone other than the proposer and the subject")}
        END IF;
        IF core.pgl_holds_platform_permission(NEW.recorded_by_user_id, 'platform.authority:manage')
           OR core.pgl_holds_platform_permission(NEW.subject_user_id, 'platform.authority:manage')
        THEN {_refuse("a holder of platform.authority:manage neither confirms nor is designated")}
        END IF;
        IF core.pgl_active_enrolment_count(NEW.subject_user_id, NULL, NULL) > 0 THEN
            {_refuse("an approver is never a representative")}
        END IF;
        NEW.designation_ref := linked.designation_ref;
        NEW.valid_until := linked.valid_until;
        IF NEW.valid_until <= now() THEN
            {_refuse("the proposed validity has passed")}
        END IF;
    ELSIF NEW.entry_type = 'approver_enrolment' THEN
        SELECT * INTO designation FROM core.{REGISTER} WHERE id = NEW.authorised_by_entry_id;
        IF NOT FOUND OR designation.entry_type <> 'representative_designation'
           OR designation.valid_until <= now()
           OR core.pgl_register_entry_revoked(designation.id) THEN
            {_refuse("an enrolment is authorised by an active designation")}
        END IF;
        IF NEW.recorded_by_user_id <> designation.subject_user_id THEN
            {_refuse("an enrolment is written by the designated representative")}
        END IF;
        IF NEW.subject_user_id = NEW.recorded_by_user_id THEN
            {_refuse("nobody enrols themselves")}
        END IF;
        IF core.pgl_holds_platform_permission(NEW.recorded_by_user_id, 'platform.authority:manage')
           OR core.pgl_holds_platform_permission(NEW.subject_user_id, 'platform.authority:manage')
           OR core.pgl_holds_platform_permission(
                  NEW.subject_user_id, 'platform.security_retention_hold:manage') THEN
            {_refuse("authority holders and hold managers are never enrolled or enrol")}
        END IF;
        IF core.pgl_has_active_designation(NEW.subject_user_id) THEN
            {_refuse("a representative is never an approver")}
        END IF;
        IF EXISTS (SELECT 1 FROM core.{REGISTER} e WHERE e.entry_type = 'approver_enrolment'
                   AND e.subject_user_id = designation.subject_user_id
                   AND e.natural_person_ref = NEW.natural_person_ref) THEN
            {_refuse("a representative never enrols their own person")}
        END IF;
        IF EXISTS (SELECT 1 FROM core.platform_operators o
                   WHERE (o.user_id = NEW.subject_user_id
                          AND o.enrolled_by_user_id = NEW.recorded_by_user_id)
                      OR (o.user_id = NEW.recorded_by_user_id
                          AND o.enrolled_by_user_id = NEW.subject_user_id))
           OR EXISTS (SELECT 1 FROM core.platform_grants g
                      JOIN core.platform_operators o ON o.id = g.operator_id
                      WHERE g.permission = 'platform.security_retention:report'
                        AND ((o.user_id = NEW.subject_user_id
                              AND g.granted_by_user_id = NEW.recorded_by_user_id)
                          OR (o.user_id = NEW.recorded_by_user_id
                              AND g.granted_by_user_id = NEW.subject_user_id))) THEN
            {_refuse("a representative never enrols someone linked to them")}
        END IF;
        NEW.eligible_from := now() + interval '120 days';
        IF NEW.valid_until IS NULL OR NEW.valid_until <= NEW.eligible_from
           OR NEW.valid_until > now() + interval '12 months' THEN
            {_refuse("an enrolment is valid for at most 12 months and beyond its delay")}
        END IF;
        IF core.pgl_active_enrolment_count(
               NEW.subject_user_id, NEW.natural_person_ref, NEW.renews_entry_id) > 0 THEN
            {_refuse("one active enrolment per account and per natural person")}
        END IF;
        IF NEW.renews_entry_id IS NOT NULL THEN
            SELECT * INTO linked FROM core.{REGISTER} WHERE id = NEW.renews_entry_id;
            IF NOT FOUND OR linked.entry_type <> 'approver_enrolment'
               OR linked.subject_user_id <> NEW.subject_user_id
               OR linked.natural_person_ref <> NEW.natural_person_ref
               OR linked.valid_until <= now()
               OR core.pgl_register_entry_revoked(linked.id)
               OR core.pgl_register_entry_revoked(linked.authorised_by_entry_id)
               OR EXISTS (SELECT 1 FROM core.{REGISTER} WHERE renews_entry_id = linked.id) THEN
                {_refuse("a renewal renews the current enrolment, once")}
            END IF;
        END IF;
    ELSIF NEW.entry_type IN ('approver_revocation', 'representative_revocation') THEN
        SELECT * INTO linked FROM core.{REGISTER} WHERE id = NEW.revokes_entry_id;
        -- No CASE inside the condition: PL/pgSQL ends an IF condition at THEN.
        revoked_kind := 'representative_designation';
        IF NEW.entry_type = 'approver_revocation' THEN
            revoked_kind := 'approver_enrolment';
        END IF;
        IF NOT FOUND OR linked.entry_type <> revoked_kind
           OR linked.subject_user_id <> NEW.subject_user_id THEN
            {_refuse("a revocation names an entry of its kind and subject")}
        END IF;
        IF core.pgl_register_entry_revoked(linked.id) THEN
            {_refuse("the entry is already revoked")}
        END IF;
        NEW.valid_until := NULL;
    END IF;
    RETURN NEW;
END
""",
    "pgl_register_before_insert",
)

