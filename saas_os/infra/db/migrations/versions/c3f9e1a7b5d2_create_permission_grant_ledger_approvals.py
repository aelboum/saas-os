def downgrade() -> None:
    # Approval records and register entries are evidence: never dropped
    # silently. The migrations role sees every row (an untenanted session).
    for table in TABLES:
        op.execute(
            "DO $$ BEGIN "
            f"IF EXISTS (SELECT 1 FROM core.{table}) THEN "
            f"RAISE EXCEPTION 'core.{table} holds rows; refusing to drop it. See "
            "docs/RUNBOOKS.md, permission grant ledger, deliberate downgrade.'; "
            "END IF; END $$"
        )
    # Dropping a table drops its policies, indexes, triggers and privileges.
    for table in TABLES:
        op.drop_table(table, schema="core")
    for function in (
        "pgl_audit_row_matches()",
        "pgl_one_way_update()",
        "pgl_authorization_before_insert()",
        "pgl_approval_before_insert()",
        "pgl_request_before_insert()",
        "pgl_refuse_change()",
        "pgl_register_before_insert()",
        "pgl_active_enrolment_count(uuid, text, uuid)",
        "pgl_has_active_designation(uuid)",
        "pgl_register_entry_revoked(uuid)",
        "pgl_holds_platform_permission(uuid, text)",
    ):
        op.execute(f"DROP FUNCTION core.{function}")
