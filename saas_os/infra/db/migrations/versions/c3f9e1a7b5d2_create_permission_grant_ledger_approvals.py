"""create the permission grant ledger approval tables and approver register

Revision ID: c3f9e1a7b5d2
Revises: a9c3e5f7b1d4
Create Date: 2026-11-03 10:00:00.000000

Owner decisions of 2026-11-02 and 2026-11-03 (ADR-0045 amendment of
2026-11-02, "Approval control"; `docs/architecture/LEDGER-DELETION-APPROVAL-
DESIGN.md`): deleting expired permission grant ledger rows needs a request,
an approval and an execution authorisation, each by an authenticated
platform-admin session, and the approver and the authoriser must hold
eligible entries in an append-only approver eligibility register. This
migration creates the four global tables that hold that state. It does not
alter the ledger (`core.permission_grant_applications`) or the holds, and it
enables no deletion: `saas_os.core.permission_grants.expiry._DELETION_ENABLED`
stays the literal `False`.

- `core.permission_grant_ledger_approver_register`: append-only entries
  (`representative_designation_proposal`, `representative_designation`,
  `representative_revocation`, `approver_enrolment`, `approver_revocation`).
  Opaque references only, never personal data. A `BEFORE INSERT` trigger
  takes the register's advisory lock, forces `recorded_at`, `eligible_from`
  (recorded_at + 120 days) and `proposal_expires_at` (recorded_at + 72 h)
  from the database clock, caps `valid_until` at 12 months, and enforces
  the relational rules: a designation confirms an unexpired, unconfirmed
  proposal, by neither its proposer nor its subject nor a holder of
  `platform.authority:manage`; an enrolment is written by the subject of an
  active designation, never for itself, never for a holder of
  `platform.authority:manage` or `platform.security_retention_hold:manage`
  or for a representative; one active enrolment per subject and per
  `natural_person_ref`, except exactly one renewal of the current entry;
  representatives and approvers stay disjoint; a revocation revokes an
  unrevoked entry of the matching kind and subject. `UPDATE` and `DELETE`
  are refused for every role.
- `core.permission_grant_ledger_deletion_requests`, `..._deletion_approvals`
  and `..._deletion_execution_authorizations`: the request (a sorted,
  distinct scope with its digest, the eligible row count and digest), the
  approval (copies of the four bound values; single use; 72 hours) and the
  execution authorisation (60 minutes, never past the approval). Triggers
  force the times from the database clock, check the copies and the
  person rules the database can see (approver is not the requester,
  authoriser is not the approver), and admit only two one-way updates on
  approvals and authorisations: the consume pair (the migrations-role
  deletion) or the invalidate pair (a register revocation), never both.
  Requests are never updated. `DELETE` is refused for every role.
- A deferred constraint trigger on each table requires the row's own
  platform audit row: a `success` row of a `user` actor equal to the row's
  `*_by_user_id`, written in the same transaction. Not authenticity: a
  holder of the application credential can write both rows.

All four carry the tenant-context exclusion policy (ADR-0045 section 9b).
None has a foreign key onto `core.platform_audit_log` (the platform test
helpers truncate it; the deferred check replaces it). The runtime role
keeps `SELECT` and `INSERT` from `e99c76057719`'s default privileges and
may `UPDATE` only `invalidated_at` and `invalidated_by_platform_audit_id`
on approvals and authorisations (a revocation runs on the runtime role);
every other `UPDATE` and every `DELETE` is revoked. The runtime role can
therefore insert register entries: whoever holds the application
credential can forge one (threat T6), detected by the audit rows, the
ADR-0053 digests and the quarterly review, never prevented. No trigger is
`SECURITY DEFINER`; each sets `search_path = pg_catalog`.

Data safety: four new, empty tables; no existing row or table changes; no
backfill. Downgrade refuses while any of the four holds a row (approval
records and register entries are evidence and are never dropped silently)
and otherwise drops them and their functions. Hand-written, not
autogenerated.
"""

