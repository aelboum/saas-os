_ONE_WAY_UPDATE = _fn(
    f"""
BEGIN
    IF OLD.consumed_at IS NOT NULL OR OLD.invalidated_at IS NOT NULL THEN
        {_refuse("a consumed or invalidated record never changes")}
    END IF;
    IF (to_jsonb(NEW) - {_FINAL_COLUMNS}) IS DISTINCT FROM (to_jsonb(OLD) - {_FINAL_COLUMNS}) THEN
        {_refuse("only the consume or the invalidate columns change")}
    END IF;
    IF NEW.consumed_at IS NOT NULL AND NEW.consumed_by_platform_audit_id IS NOT NULL
       AND NEW.invalidated_at IS NULL AND NEW.invalidated_by_platform_audit_id IS NULL THEN
        NEW.consumed_at := clock_timestamp();
        IF NEW.consumed_at >= OLD.expires_at THEN
            {_refuse("an expired record is never consumed")}
        END IF;
        RETURN NEW;
    END IF;
    IF NEW.invalidated_by_platform_audit_id IS NOT NULL
       AND NEW.consumed_at IS NULL AND NEW.consumed_by_platform_audit_id IS NULL THEN
        NEW.invalidated_at := clock_timestamp();
        RETURN NEW;
    END IF;
    {_refuse("a record is consumed or invalidated, once, never both")}
END
""",
    "pgl_one_way_update",
)

# Deferred to the commit: the row's audit row exists, is a `success` of a
# `user` actor equal to the row's user column (when one is named), and was
# written in this transaction (`created_at` is the transaction's `now()`).
_AUDIT_ROW = _fn(
    """
DECLARE
    audit_id uuid := (to_jsonb(NEW) ->> TG_ARGV[0])::uuid;
    actor uuid := CASE WHEN TG_ARGV[1] = '-' THEN NULL
                       ELSE (to_jsonb(NEW) ->> TG_ARGV[1])::uuid END;
    action_pattern text := CASE WHEN TG_ARGV[2] <> 'by_entry_type' THEN TG_ARGV[2]
        ELSE CASE to_jsonb(NEW) ->> 'entry_type'
            WHEN 'representative_designation_proposal'
                THEN '^platform[.]permission_grant_ledger[.]representative_propose$'
            WHEN 'representative_designation'
                THEN '^platform[.]permission_grant_ledger[.]representative_confirm$'
            WHEN 'representative_revocation'
                THEN '^platform[.]permission_grant_ledger[.]'
                     || 'representative_revoke_by_(owner|security)$'
            WHEN 'approver_enrolment'
                THEN '^platform[.]permission_grant_ledger[.]approver_enrol$'
            WHEN 'approver_revocation'
                THEN '^platform[.]permission_grant_ledger[.]'
                     || 'approver_revoke_by_(representative|security)$'
            END
        END;
BEGIN
    IF audit_id IS NULL THEN
        RETURN NULL;
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM core.platform_audit_log l
        WHERE l.id = audit_id AND l.outcome = 'success' AND l.actor_type = 'user'
          AND (actor IS NULL OR l.actor_user_id = actor)
          AND l.action ~ action_pattern
          AND l.created_at = now()) THEN
        RAISE EXCEPTION '%.% names no audit row of its own act in this transaction (%)',
            TG_TABLE_SCHEMA, TG_TABLE_NAME, TG_ARGV[0] USING ERRCODE = 'check_violation';
    END IF;
    RETURN NULL;
END
""",
    "pgl_audit_row_matches",
)


