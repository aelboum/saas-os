def _role(variable: str, default: str) -> str:
    role = os.environ.get(variable, default)
    if not _IDENTIFIER.fullmatch(role):
        raise ValueError(f"{variable} must be a plain SQL identifier, got: {role!r}")
    return role


def _roles() -> tuple[str, str]:
    app_role = _role("APP_DB_USER", _DEFAULT_APP_ROLE)
    config_role = _role("PLATFORM_CONFIG_DB_USER", _DEFAULT_PLATFORM_CONFIG_ROLE)
    if app_role == config_role:
        raise ValueError("PLATFORM_CONFIG_DB_USER must differ from APP_DB_USER.")
    return app_role, config_role


def _trigger(table: str) -> str:
    return f"trg_{table.split('.')[1]}_refuse_platform_config_update"


def _ensure_role(bind: sa.Connection, app_role: str, config_role: str) -> None:
    row = bind.execute(
        sa.text("SELECT rolsuper, rolbypassrls, rolcreaterole FROM pg_roles WHERE rolname = :r"),
        {"r": config_role},
    ).one_or_none()
    if row is None:
        op.execute(
            f'CREATE ROLE "{config_role}" NOLOGIN NOSUPERUSER NOBYPASSRLS '
            "NOCREATEDB NOCREATEROLE NOREPLICATION"
        )
    elif row.rolsuper or row.rolbypassrls or row.rolcreaterole:
        raise RuntimeError(
            f"Role {config_role!r} is a superuser, BYPASSRLS or CREATEROLE; "
            "the platform-configuration role must be none of these."
        )
    related = bind.execute(
        sa.text(
            "SELECT pg_has_role(:a, :c, 'MEMBER') OR pg_has_role(:c, :a, 'MEMBER') "
            "FROM pg_roles WHERE rolname = :a"
        ),
        {"a": app_role, "c": config_role},
    ).scalar_one_or_none()
    if related:
        raise RuntimeError(
            f"Roles {app_role!r} and {config_role!r} are in a membership; "
            "the platform-configuration role must be separate from the application role."
        )


