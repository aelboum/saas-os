"""index core.audit_log on the tenant audit subject reference keys

Revision ID: d4f8b2e6a9c1
Revises: c7e3a9f2b4d8
Create Date: 2026-11-15 22:00:00.000000

Audit identity phase P3b, migration M2 of
`docs/architecture/AUDIT-IDENTITY-P3-PLAN.md` (approved by the owner on
2026-11-15, question Q3: build the index `CONCURRENTLY` inside the
migration). Two additive, partial expression indexes:

    ix_audit_log_initiated_by_subject_ref
        ON core.audit_log (tenant_id, ((metadata -> 'initiated_by') ->> 'subject_ref'))
        WHERE (metadata -> 'initiated_by') ->> 'subject_ref' IS NOT NULL
    ix_audit_log_owner_user_subject_ref
        ON core.audit_log (tenant_id, (metadata ->> 'owner_user_subject_ref'))
        WHERE metadata ->> 'owner_user_subject_ref' IS NOT NULL

They serve the tenant expiry record bound (P3c): for one tenant reference,
the newest audit row that carries it, under either key. Partial, because
only rows written since P3a (`c7e3a9f2b4d8`) carry a reference: no row
written before is ever in them. `metadata` is `json`, and `->` / `->>` on
`json` are immutable, so the expressions are indexable.

**Data safety.** Additive and backwards compatible. No table, column,
constraint, policy, privilege or row is changed, and nothing is written to
any row. Writes do not depend on the indexes; existing code runs unchanged
with or without them. `downgrade()` drops them and restores the schema
exactly; no data is lost in either direction.

**Locking.** A plain `CREATE INDEX` takes SHARE on `core.audit_log` and
blocks every audited write for the whole table scan. `CREATE INDEX
CONCURRENTLY` takes SHARE UPDATE EXCLUSIVE, which does not conflict with
inserts or reads, so audited writes continue during the build. The build
still scans the table (twice) and waits for transactions older than each
phase to finish, so its duration grows with the table and with the longest
open transaction. It is not bounded by a lock timeout on purpose: waiting
blocks no write, while a timeout would throw away a long scan.

**Transactions.** `CONCURRENTLY` cannot run in a transaction block, and
saas_os/infra/db/migrations/env.py runs every pending revision in one
transaction, so the work runs inside `autocommit_block()` (precedent:
`f0cc2e656d79`). Alembic first COMMITs the open transaction -- every
earlier revision of the same run and its stamp -- and then runs each
statement in its own transaction. Consequence: if this revision fails, the
database is left at `c7e3a9f2b4d8`, not at the head before the run, and
`saas-os-migrate upgrade` runs only this revision again.

**Failure and pre-build.** A failed concurrent build leaves an INVALID
index behind. Before each build an invalid index of that name is dropped
`CONCURRENTLY`; if the build itself fails, the invalid index it left is
dropped the same way and the migration fails with a message naming it.
`IF NOT EXISTS` lets an operator build the same index beforehand, during
a quiet period, with the statement above: the migration then finds it.
Either way, the migration finally checks that each index is valid, ready,
on `core.audit_log`, partial, and keyed on its reference key, and fails
naming the index otherwise. A valid index of that name with another
definition is not dropped: it is the operator's object, and the failure
says so.

Offline SQL (`alembic ... --sql`) is not a supported way to apply this
revision: the checks need a live connection. Use `saas-os-migrate
upgrade`.

**Downgrade.** A plain `DROP INDEX IF EXISTS`, in the run's transaction,
not `CONCURRENTLY` in an autocommit block: a downgrade that runs past this
revision and is refused by an earlier one (the P3a downgrade refuses while
its tables hold rows) must change nothing. An autocommitted drop would stay
dropped while the stamp rolled back to this revision, and a later `upgrade
head` would then not build the indexes again. The cost: the drop takes
ACCESS EXCLUSIVE on `core.audit_log` and holds it until the downgrade run
commits, so audited writes wait for that long. No data is involved.
Hand-written, not autogenerated.
"""

