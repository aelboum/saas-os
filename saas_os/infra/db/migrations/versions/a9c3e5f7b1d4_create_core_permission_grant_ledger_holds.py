"""create core permission_grant_ledger_holds table

Revision ID: a9c3e5f7b1d4
Revises: e8f3b1d5a2c7
Create Date: 2026-11-02 09:00:00.000000

Owner policy of 2026-11-02 for the permission grant ledger
(`core.permission_grant_applications`, ADR 0060): the ledger stays
`SECURITY_RETAIN`; its default retention ends two years after the tenant
reached `PURGED`; a documented legal hold may extend it. This table is the
durable state of those legal holds. It does not alter the ledger table.

One row per hold placed on one tenant's ledger rows: the tenant
(`target_tenant_id`), an opaque reference to the legal matter (an
identifier-shaped string, never a name or personal data), when it was
placed and the id of the platform audit row that placed it, and, once
released, when and the id of the platform audit row that released it. A
hold is active while `released_at` is NULL; a released hold stays as
history.

Global, platform-owned: it holds operator decisions about an installation,
not a tenant's data, and a hold must outlive the tenant's own data. It
carries the tenant-context exclusion policy of the platform-authority
tables (`c4a9e1f07b52`; ADR-0045 section 9b), so no tenant-scoped
transaction can read or change it. `target_tenant_id` has a `NO ACTION`
foreign key onto `core.tenants` (a hold names a real tenant, and like the
ledger it keeps the tombstone). The runtime role keeps SELECT and INSERT
from `e99c76057719`'s default privileges and may UPDATE only `released_at`
and `released_by_platform_audit_id` (a release); DELETE is revoked, so the
application never removes or rewrites a hold. A release is one-way: a
`BEFORE UPDATE` trigger refuses any change to a released hold
(`check_violation`), whichever role makes it.

Placing and releasing a hold are platform operations
(`permission_grant_ledger.hold_place`, `permission_grant_ledger.hold_release`)
under `platform.security_retention_hold:manage`; the eligibility report
(`permission_grant_ledger.retention_report`) is under
`platform.security_retention:report` (owner decision A of 2026-11-02:
least-privilege permissions, separate from `platform.permission_grant:apply`).

`core.platform_grants.permission`: the CHECK `ck_platform_grants_permission`
is widened from `d7e2a9c4f1b6`'s twenty-six permissions to twenty-eight
with those two. Written out literally; `PLATFORM_PERMISSIONS_BEFORE` is
`d7e2a9c4f1b6`'s list verbatim. The widening lives here, with the feature
that needs it, so the migration head stays `a9c3e5f7b1d4`.

Data safety: a new, empty table; no existing row changes, no backfill. The
CHECK widening accepts every existing row (brief ACCESS EXCLUSIVE lock on
`core.platform_grants` for the swap). Downgrade refuses while the table
holds any hold, active or released (a hold is retention evidence and is
never dropped silently), and while any `core.platform_grants` row names one
of the two permissions, revoked or not (revocation keeps the row, and the
first owner receives the report permission at bootstrap -- hold management
is withheld for separation of duties -- so on a bootstrapped installation
treat it as irreversible). With neither, it restores the twenty-six
permission CHECK and drops the table, its trigger function and policy.
Removing holds or grants to allow a downgrade is a separately approved
manual procedure (`docs/RUNBOOKS.md`). Hand-written, not autogenerated.
"""

